/**
 * 平台经济模型
 * ------------------------------------------------------------------
 * 【筹码】玩家在房间内使用的游戏货币，由代理开房时设定初始值、
 *   对局中可由房主临时上分（赠送）。玩家不持有信用分，也不需要信用分。
 *
 * 【信用分】仅代理 / 总代理持有，是平台向代理收取"水费"的账户。
 *   1 信用分 = 1 筹码流水额度，由客服手动增减，平台不涉及充值提现。
 *
 * 【平台收入】
 *   1. 游戏内抽水：每局从赢家赢得的筹码中抽取 3%（直接从游戏筹码中扣除）
 *   2. 代理信用分扣除：每局按流水的 2% 累计，25局结束（或提前结束）从房主代理信用分扣除
 *
 * 【平台支出（返佣）】
 *   1. 代理返佣：流水的 1%，累计到代理返佣账户，提现联系客服
 *   2. 总代理返佣：下线代理开房流水的 1%，自动计入总代理信用分
 *
 * 【平台净收入】= 3%（游戏内抽水）+ 2%（代理信用分扣）- 1%（代理返佣）- 1%（总代理返佣）= 3%流水
 * ------------------------------------------------------------------
 */

