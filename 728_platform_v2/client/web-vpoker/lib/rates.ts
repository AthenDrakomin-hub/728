/**
 * 平台经济模型
 * ------------------------------------------------------------------
 * 【筹码】玩家在房间内使用的游戏货币，由代理开房时设定初始值、
 *   对局中可由房主临时上分（赠送）。玩家不持有信用分，也不需要信用分。
 *
 * 【信用分】仅代理 / 总代理持有，是平台向代理收取"水费"的账户。
 *   1 信用分 = 1 筹码流水额度，由客服手动增减，平台不涉及充值提现。
 *
 * 【水费结算】每局从赢家赢得的筹码中抽取 3% 记为水费（房间累计）。
 *   一个总局（25 局）结束后，把累计水费全额从房主代理的信用分中扣除。
 *   例：25 局共产生 300 水费 → 结算时扣除房主 300 信用分。
 * ------------------------------------------------------------------
 */

/** 每局房费比例（从赢家赢得的筹码中抽取，累计为房间房费） */
export const PLATFORM_RAKE = 0.03;

/**
 * 总代理分成：按水费的 1/3 返给上级总代理
 * （水费=流水的 3%，其 1/3 即流水的 1%，对应"总代理抽 1%"）
 */
export const TOP_AGENT_SHARE = 1 / 3;

